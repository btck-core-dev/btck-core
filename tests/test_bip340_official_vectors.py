class TestBIP340OfficialVectors(unittest.TestCase):
    def test_official_signing_vectors(self):
        for secret_hex, public_hex, aux_hex, message_hex, signature_hex in SIGNING_VECTORS:
            secret = int(secret_hex, 16)
            message = bytes.fromhex(message_hex)
            expected_public = bytes.fromhex(public_hex)
            expected_signature = bytes.fromhex(signature_hex)
            self.assertEqual(bip340_pubkey(secret), expected_public)
            self.assertEqual(schnorr_sign(secret, message, bytes.fromhex(aux_hex)), expected_signature)
            self.assertTrue(schnorr_verify(expected_public, message, expected_signature))

    def test_official_invalid_vectors(self):
        message = bytes.fromhex("243F6A8885A308D313198A2E03707344A4093822299F31D0082EFA98EC4E6C89")
        for public_hex, signature_hex in INVALID_VECTORS:
            self.assertFalse(schnorr_verify(bytes.fromhex(public_hex), message, bytes.fromhex(signature_hex)))

    def test_rejects_nonstandard_signature_length(self):
        public = bytes.fromhex(SIGNING_VECTORS[0][1])
        message = bytes.fromhex(SIGNING_VECTORS[0][3])
        signature = bytes.fromhex(SIGNING_VECTORS[0][4])
        self.assertFalse(schnorr_verify(public, message, signature + b"\x00"))


